	on storage.objects for delete to authenticated
	using (
		bucket_id = 'asset-attachments'
		and (
			storage.filename(name) like (select auth.uid())::text || '-%'
			or coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), 'user') = 'admin'
		)
	);

-- Enable live updates across signed-in devices through Supabase Realtime.
do $$
begin
	if not exists (
		select 1 from pg_publication_tables
		where pubname = 'supabase_realtime'
			and schemaname = 'public'
			and tablename = 'assets'
	) then
		execute 'alter publication supabase_realtime add table public.assets';
	end if;
end;
$$;
