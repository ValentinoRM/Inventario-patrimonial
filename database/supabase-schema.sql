create index if not exists assets_location_idx on public.assets (location);
create index if not exists assets_maintenance_due_idx on public.assets (maintenance_due) where maintenance_due is not null;

create table if not exists public.asset_history (
	id bigint generated by default as identity primary key,
	asset_id uuid not null,
	asset_code text not null,
	event_type text not null check (event_type in ('created', 'updated', 'transferred', 'deleted')),
	changed_by uuid references auth.users(id) on delete set null,
	old_data jsonb,
	new_data jsonb,
	created_at timestamptz not null default now()
);

create index if not exists asset_history_asset_created_idx on public.asset_history (asset_id, created_at desc);
alter table public.asset_history enable row level security;
grant select on public.asset_history to authenticated;
revoke insert, update, delete on public.asset_history from authenticated;

drop policy if exists "Authenticated users can read asset history" on public.asset_history;
create policy "Authenticated users can read asset history"
	on public.asset_history for select to authenticated
	using (coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), 'user') in ('admin', 'user'));

create or replace function public.record_asset_history()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
	event_name text;
	old_snapshot jsonb;
	new_snapshot jsonb;
	target_id uuid;
	target_code text;
begin
	if tg_op = 'INSERT' then
		event_name := 'created';
		new_snapshot := to_jsonb(new);
		target_id := new.id;
		target_code := new.asset_code;
	elsif tg_op = 'DELETE' then
		event_name := 'deleted';
		old_snapshot := to_jsonb(old);
		target_id := old.id;
		target_code := old.asset_code;
	else
		old_snapshot := to_jsonb(old);
		new_snapshot := to_jsonb(new);
		target_id := new.id;
		target_code := new.asset_code;
		if old.zone is distinct from new.zone or old.location is distinct from new.location or old.custodian is distinct from new.custodian then
			event_name := 'transferred';
		else
			event_name := 'updated';
		end if;
	end if;

	insert into public.asset_history (asset_id, asset_code, event_type, changed_by, old_data, new_data)
	values (
		target_id,
		target_code,
		event_name,
		(select auth.uid()),
		old_snapshot,
		new_snapshot
	);

	if tg_op = 'DELETE' then return old; end if;
	return new;
end;
$$;

drop trigger if exists assets_record_history on public.assets;
create trigger assets_record_history
after insert or update or delete on public.assets
for each row execute function public.record_asset_history();

create table if not exists public.asset_checks (
	id bigint generated by default as identity primary key,
	asset_id uuid not null references public.assets(id) on delete cascade,
	status text not null check (status in ('verified', 'missing', 'needs_attention')),
	notes text not null default '',
	checked_by uuid not null default auth.uid() references auth.users(id),
	checked_at timestamptz not null default now()
