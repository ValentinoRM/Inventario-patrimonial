	on public.assets for insert to authenticated
	with check (
		coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), 'user') in ('admin', 'user')
		and created_by = (select auth.uid())
		and updated_by = (select auth.uid())
	);

